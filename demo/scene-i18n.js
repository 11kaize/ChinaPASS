  function add(target, key, lang, value) {
    if (value == null || target[key] == null) return;
    if (typeof target[key] === "string") target[key] = { en: target[key] };
    target[key][lang] = value;
  }

  function requireLength(scene, field, translated, expected) {
    if (!translated || translated.length !== expected) {
      throw new Error(`Scene translation length mismatch: ${scene.id}.${field}`);
    }
  }

  function mergeScene(scene, lang, copy) {
    ["task", "tip", "disclaimer"].forEach((key) => add(scene, key, lang, copy[key]));

    ["before", "planB"].forEach((field) => {
      const source = scene[field] || [];
      const translated = copy[field];
      if (!translated && !source.length) return;
      requireLength(scene, field, translated, source.length);
      source.forEach((item, index) => add(source, index, lang, translated[index]));
    });

    const groups = [
      ["steps", ["t", "d"]],
      ["mistakes", ["m", "w", "d"]],
      ["trouble", ["p", "a"]],
    ];
    groups.forEach(([field, keys]) => {
      const source = scene[field] || [];
      const translated = copy[field];
      if (!translated && !source.length) return;
      requireLength(scene, field, translated, source.length);
      source.forEach((item, index) => {
        requireLength(scene, `${field}[${index}]`, translated[index], keys.length);
        keys.forEach((key, keyIndex) => add(item, key, lang, translated[index][keyIndex]));
      });
    });

    if (scene.showCard && copy.showCardTitle) add(scene.showCard, "title", lang, copy.showCardTitle);
  }

