import sharp from 'sharp';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'assets');
const output = path.join(assets, 'optimized');
// Original generated artwork stays untouched. Encode derivatives at phone sizes.
const specs = [
  ['brand', 'brand-blue', 256, 100],
  ['skyline', 'skyline', 960, 82],
  ['homeDay', 'home-portrait', 768, 82],
  ['homeNight', 'home-night', 768, 84],
  ['arrivalDay', 'arrival-hero', 960, 82],
  ['arrivalNight', 'arrival-night', 960, 84],
  ['login', 'login-gateway', 768, 82],
  ['assistant', 'ai-companion', 256, 88],
  ['foodDay', 'community-food', 576, 82],
  ['foodNight', 'community-food-night', 576, 82],
];
await mkdir(output, { recursive: true });
const inline = {}, report = [];
for (const [key, name, width, quality] of specs) {
  const source = await readFile(path.join(assets, `${name}.png`));
  const { data, info } = await sharp(source)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality, alphaQuality: 100, effort: 6, lossless: key === 'brand' })
    .toBuffer({ resolveWithObject: true });
  await writeFile(path.join(output, `${name}.webp`), data);
  inline[key] = { uri: `data:image/webp;base64,${data.toString('base64')}`, width: info.width, height: info.height };
  report.push({ key, sourceBytes: source.length, encodedBytes: data.length, width: info.width, height: info.height });
}
await writeFile(path.join(root, 'src/artwork.web.ts'),
  '// Generated by npm run assets:prepare. Web artwork is embedded in the app bundle.\n' +
  `export const artwork = ${JSON.stringify(inline)} as const;\n`);
await writeFile(path.join(root, 'src/artwork.ts'),
  '// Generated by npm run assets:prepare. Native artwork is packaged as local assets.\n' +
  `export const artwork = {\n${specs.map(([key, name]) => `  ${key}: require("../assets/${name}.png"),`).join('\n')}\n} as const;\n`);
await writeFile(path.join(output, 'manifest.json'), JSON.stringify(report, null, 2) + '\n');
const sourceBytes = report.reduce((sum, r) => sum + r.sourceBytes, 0);
const encodedBytes = report.reduce((sum, r) => sum + r.encodedBytes, 0);
console.log(`Artwork: ${report.length} assets; ${sourceBytes} → ${encodedBytes} bytes (${(100 * (1 - encodedBytes / sourceBytes)).toFixed(1)}% smaller); web images embedded.`);
