import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { svgToIcon } from "morphicons/adapters";
import { toRegion } from "morphicons/region";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const definitions = path.join(
  root,
  "node_modules/phosphor-react-native/src/defs",
);
// Reuse the installed icon artwork, never redraw or substitute another family.
const icons = {
  today: ["House", "regular", "fill"],
  community: ["UsersThree", "regular", "fill"],
  cards: ["Translate", "regular", "fill"],
  chat: ["ChatCircleDots", "regular", "fill"],
  profile: ["UserCircle", "regular", "fill"],
  save: ["BookmarkSimple", "regular", "fill"],
  heart: ["Heart", "regular", "fill"],
  send: ["PaperPlaneTilt", "fill"],
  stop: ["Stop", "fill"],
  unchecked: ["Circle", "regular"],
  checked: ["CheckCircle", "regular"],
  search: ["MagnifyingGlass", "regular"],
  close: ["X", "regular"],
  next: ["CaretRight", "regular"],
  down: ["CaretDown", "regular"],
};
const tagNames = new Set([
  "Path",
  "Circle",
  "Ellipse",
  "Rect",
  "Line",
  "Polyline",
  "Polygon",
  "G",
]);
const escape = (value) =>
  String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;");
function markup(node) {
  if (ts.isJsxFragment(node)) return node.children.map(markup).join("");
  if (ts.isJsxText(node)) return "";
  if (ts.isJsxSelfClosingElement(node) || ts.isJsxElement(node)) {
    const opening = ts.isJsxElement(node) ? node.openingElement : node;
    const tag = opening.tagName.getText();
    if (!tagNames.has(tag))
      throw new Error(`Unsupported Phosphor SVG element: ${tag}`);
    const attrs = opening.attributes.properties
      .map((attribute) => {
        if (!ts.isJsxAttribute(attribute) || !attribute.initializer)
          throw new Error("Expected static SVG attributes");
        const name = attribute.name
          .getText()
          .replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
        const init = attribute.initializer;
        let value;
        if (ts.isStringLiteral(init)) value = init.text;
        else if (
          ts.isJsxExpression(init) &&
          init.expression &&
          ts.isNumericLiteral(init.expression)
        )
          value = init.expression.text;
        else throw new Error(`Non-static SVG attribute ${name}`);
        return ` ${name}="${escape(value)}"`;
      })
      .join("");
    const children = ts.isJsxElement(node)
      ? node.children.map(markup).join("")
      : "";
    return `<${tag.toLowerCase()}${attrs}>${children}</${tag.toLowerCase()}>`;
  }
  throw new Error(`Unsupported static SVG node: ${ts.SyntaxKind[node.kind]}`);
}
const output = {};
for (const [name, [definition, ...weights]] of Object.entries(icons)) {
  const file = ts.createSourceFile(
    `${definition}.tsx`,
    await readFile(path.join(definitions, `${definition}.tsx`), "utf8"),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );
  for (const weight of weights) {
    let found;
    const visit = (node) => {
      if (
        ts.isArrayLiteralExpression(node) &&
        node.elements.length === 2 &&
        ts.isStringLiteral(node.elements[0]) &&
        node.elements[0].text === weight
      )
        found = node.elements[1];
      ts.forEachChild(node, visit);
    };
    visit(file);
    if (!found)
      throw new Error(`Missing Phosphor weight: ${definition}/${weight}`);
    const svg = `<svg viewBox="0 0 256 256" fill="currentColor">${markup(found)}</svg>`;
    output[`${name}:${weight}`] = toRegion(svgToIcon(svg));
  }
}
await mkdir(path.join(root, "src/generated"), { recursive: true });
await writeFile(
  path.join(root, "src/generated/motion-icons.ts"),
  `// Generated by scripts/prepare-motion-icons.mjs. Phosphor artwork (MIT); see NOTICE.md.\n// Regions are prepared at build time: no SVG parsing, icon fetch or contour normalization on interaction.\nimport type { IconNode } from "morphicons";\nexport const motionIcons: Record<string, IconNode> = ${JSON.stringify(output)};\n`,
);
console.log(
  `Prepared ${Object.keys(output).length} local Phosphor morph shapes.`,
);
